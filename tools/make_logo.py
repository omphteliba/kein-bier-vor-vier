"""Generates the dial logo: twelve times the same digit, beer in the lower half,
hands at four (or five) o'clock.

Writes SVGs for viewing (docs/logo/) and the adaptive launcher icon used by
phone and watch (common/src/main/res/). Run from the repository root:

    python tools/make_logo.py
"""
import math
from pathlib import Path

CREAM, AMBER, DARK_AMBER = '#FDF6E3', '#F6B400', '#D98300'
INK, RED, NIGHT = '#595540', '#C62828', '#15120C'

# Digit glyphs in a 10 x 14 box (blocky, readable at icon size).
GLYPHS = {
    4: 'M6,0 H8.6 V8.4 H10 V10.6 H8.6 V14 H6.1 V10.6 H0 V8.5 Z M6.1,3.6 L2.6,8.4 H6.1 Z',
    5: ('M1,0 H9.5 V2.3 H3.3 L3,5.2 C3.9,4.8 4.9,4.6 5.9,4.6 C8.4,4.6 10,6.4 10,9.2 '
        'C10,12 8,14 5.1,14 C2.8,14 1,12.9 0.3,11 L2.5,10.1 C2.9,11.2 3.8,11.8 5,11.8 '
        'C6.6,11.8 7.6,10.7 7.6,9.2 C7.6,7.7 6.6,6.7 5.1,6.7 C4.1,6.7 3.3,7.1 2.7,7.7 L0.6,7.2 Z'),
}

SIZE = 108          # adaptive icon viewport
C = SIZE / 2        # centre
R = 31              # dial radius: diameter 62 fits the 66 dp safe zone
DIGIT_RADIUS = 22.5
DIGIT_SCALE = 0.46  # glyph height 14 -> ~6.4
FOAM = [(-30, 2.6), (-24.5, 3.4), (-18.5, 2.8), (-12.5, 3.6), (-6, 3.0), (0, 3.6),
        (6, 3.0), (12.5, 3.6), (18.5, 2.8), (24.5, 3.4), (30, 2.6)]


def hand(angle_deg, length):
    a = math.radians(angle_deg)
    return C + length * math.sin(a), C - length * math.cos(a)


def digit_transforms():
    for i in range(12):
        a = math.radians(i * 30)
        x = C + DIGIT_RADIUS * math.sin(a) - 5 * DIGIT_SCALE
        y = C - DIGIT_RADIUS * math.cos(a) - 7 * DIGIT_SCALE
        yield round(x, 2), round(y, 2)


def svg(digit, background=True):
    hx, hy = hand(digit * 30, 11.5)  # hour hand on the digit's hour
    mx, my = hand(0, 16.5)          # minute hand on twelve, clear of the digit
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" width="512" height="512">',
             '<defs>',
             f'<clipPath id="dial"><circle cx="{C}" cy="{C}" r="{R}"/></clipPath>',
             f'<linearGradient id="beer" x1="0" y1="{C}" x2="0" y2="{C + R}" gradientUnits="userSpaceOnUse">'
             f'<stop offset="0" stop-color="{AMBER}"/><stop offset="1" stop-color="{DARK_AMBER}"/></linearGradient>',
             '</defs>']
    if background:
        parts.append(f'<rect width="{SIZE}" height="{SIZE}" fill="{NIGHT}"/>')
    parts += [f'<circle cx="{C}" cy="{C}" r="{R}" fill="{CREAM}"/>',
              '<g clip-path="url(#dial)">',
              f'<rect x="0" y="{C}" width="{SIZE}" height="{C}" fill="url(#beer)"/>',
              *[f'<circle cx="{C + dx}" cy="{C}" r="{r}" fill="#FFFFFF"/>' for dx, r in FOAM],
              f'<rect x="0" y="{C - 0.5}" width="{SIZE}" height="2" fill="#FFFFFF"/>',
              '</g>',
              f'<circle cx="{C}" cy="{C}" r="{R - 1.25}" fill="none" stroke="{INK}" stroke-width="2.5"/>',
              *[f'<path transform="translate({x},{y}) scale({DIGIT_SCALE})" d="{GLYPHS[digit]}" fill="{INK}" fill-rule="evenodd"/>'
                for x, y in digit_transforms()],
              f'<line x1="{C}" y1="{C}" x2="{hx:.2f}" y2="{hy:.2f}" stroke="{INK}" stroke-width="2.8" stroke-linecap="round"/>',
              f'<line x1="{C}" y1="{C}" x2="{mx:.2f}" y2="{my:.2f}" stroke="{INK}" stroke-width="2" stroke-linecap="round"/>',
              f'<circle cx="{C}" cy="{C}" r="2" fill="{RED}"/>',
              '</svg>']
    return '\n'.join(parts) + '\n'


def vector(digit):
    """Android vector drawable (adaptive icon foreground) with the same geometry."""
    hx, hy = hand(digit * 30, 11.5)
    mx, my = hand(0, 16.5)

    def circle(cx, cy, r):
        return f'M{cx - r},{cy} a{r},{r} 0 1,1 {2 * r},0 a{r},{r} 0 1,1 -{2 * r},0 Z'

    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/make_logo.py - edit the script, not this file. -->',
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    xmlns:aapt="http://schemas.android.com/aapt"',
             f'    android:width="{SIZE}dp" android:height="{SIZE}dp"',
             f'    android:viewportWidth="{SIZE}" android:viewportHeight="{SIZE}">',
             f'    <path android:fillColor="{CREAM}" android:pathData="{circle(C, C, R)}" />',
             '    <group>',
             f'        <clip-path android:pathData="{circle(C, C, R)}" />',
             f'        <path android:pathData="M0,{C} H{SIZE} V{SIZE} H0 Z">',
             '            <aapt:attr name="android:fillColor">',
             f'                <gradient android:type="linear" android:startX="0" android:startY="{C}" android:endX="0" android:endY="{C + R}"',
             f'                    android:startColor="{AMBER}" android:endColor="{DARK_AMBER}" />',
             '            </aapt:attr>',
             '        </path>',
             *[f'        <path android:fillColor="#FFFFFF" android:pathData="{circle(C + dx, C, r)}" />' for dx, r in FOAM],
             f'        <path android:fillColor="#FFFFFF" android:pathData="M0,{C - 0.5} H{SIZE} V{C + 1.5} H0 Z" />',
             '    </group>',
             f'    <path android:strokeColor="{INK}" android:strokeWidth="2.5" android:pathData="{circle(C, C, R - 1.25)}" />']
    for x, y in digit_transforms():
        lines += [f'    <group android:translateX="{x}" android:translateY="{y}" android:scaleX="{DIGIT_SCALE}" android:scaleY="{DIGIT_SCALE}">',
                  f'        <path android:fillColor="{INK}" android:fillType="evenOdd" android:pathData="{GLYPHS[digit]}" />',
                  '    </group>']
    lines += [f'    <path android:strokeColor="{INK}" android:strokeWidth="2.8" android:strokeLineCap="round" android:pathData="M{C},{C} L{hx:.2f},{hy:.2f}" />',
              f'    <path android:strokeColor="{INK}" android:strokeWidth="2" android:strokeLineCap="round" android:pathData="M{C},{C} L{mx:.2f},{my:.2f}" />',
              f'    <path android:fillColor="{RED}" android:pathData="{circle(C, C, 2)}" />',
              '</vector>']
    return '\n'.join(lines) + '\n'


def write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    write('docs/logo/logo-vier.svg', svg(4))
    write('docs/logo/logo-five.svg', svg(5))
    res = Path('common/src/main/res')
    # English (default): 5 o'clock somewhere; German: kein Bier vor Vier.
    write(res / 'drawable/ic_launcher_foreground.xml', vector(5))
    write(res / 'drawable-de/ic_launcher_foreground.xml', vector(4))
    print('ok')
