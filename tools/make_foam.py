"""Generates the wavy foam band for the places that can't draw it themselves:
the phone widget (vector drawable) and the watch face (PNG, needs ImageMagick).
Same shape as the app's foam (common/.../BeerGlass.kt). Run from the repo root:

    python tools/make_foam.py
"""
import math
import subprocess
from pathlib import Path

FOAM, PORE, AMBER = '#FFFCF2', '#F3E7C9', '#F6B400'


def band(width, centre, thickness, amplitude, wavelength, step=2.0):
    """Polygon points of the foam band: wavy top edge, then the bottom edge back."""
    def edge(x, side, phase):
        return centre + side * thickness / 2 + amplitude * math.sin(x / wavelength * 2 * math.pi + phase)

    xs = [min(i * step, width) for i in range(int(width / step) + 2)]
    top = [(x, edge(x, -1, 0)) for x in xs]
    bottom = [(x, edge(x, 1, 2.2)) for x in reversed(xs)]
    return top + bottom


def path_data(points):
    head, *rest = points
    return f'M{head[0]:.1f},{head[1]:.1f} ' + ' '.join(f'L{x:.1f},{y:.1f}' for x, y in rest) + ' Z'


def pores(width, centre, thickness, amplitude, wavelength, r):
    for fx, fy in [(0.10, 0.15), (0.27, -0.2), (0.46, 0.25), (0.64, -0.1), (0.83, 0.2), (0.95, -0.15)]:
        x = fx * width
        yield x, centre + fy * thickness + amplitude * math.sin(x / wavelength * 2 * math.pi + 1.1), r


def widget_vector():
    w, h, c = 200, 28, 13
    shape = (w, c, 12, 3, 80)
    circles = '\n'.join(
        f'    <path android:fillColor="{PORE}" android:pathData="M{x - r:.1f},{y:.1f} a{r},{r} 0 1,1 {2 * r},0 a{r},{r} 0 1,1 -{2 * r},0 Z" />'
        for x, y, r in pores(*shape, r=1.1))
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_foam.py - edit the script, not this file.
     Wavy foam between the cream glass and the beer, like in the app. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{w}dp"
    android:height="{h}dp"
    android:viewportWidth="{w}"
    android:viewportHeight="{h}">
    <path android:fillColor="{AMBER}" android:pathData="M0,{c} H{w} V{h} H0 Z" />
    <path android:fillColor="{FOAM}" android:pathData="{path_data(band(*shape))}" />
{circles}
</vector>
'''


def watch_face_png(out):
    w, h, c = 450, 44, 22
    shape = (w, c, 22, 6, 200)
    circles = ''.join(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="{PORE}"/>' for x, y, r in pores(*shape, r=2.2))
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">'
           f'<path d="{path_data(band(*shape))}" fill="{FOAM}"/>{circles}</svg>')
    tmp = Path(out).with_suffix('.svg')
    tmp.write_text(svg, encoding='utf-8')
    subprocess.run(['magick', '-background', 'none', str(tmp), str(out)], check=True)
    tmp.unlink()


if __name__ == '__main__':
    Path('phone/src/main/res/drawable/widget_foam.xml').write_text(widget_vector(), encoding='utf-8')
    watch_face_png('watchface/src/main/res/drawable-nodpi/foam.png')
    print('ok')
