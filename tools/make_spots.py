"""Generates the Kotlin list of places and breweries from data/spots.json,
and copies the JSON into the Swift package for the iOS and watchOS apps.
Run from the repository root after editing the JSON:

    python tools/make_spots.py           # write the Kotlin file
    python tools/make_spots.py --check   # fail if it is out of date (CI)
"""
import json
import sys
from pathlib import Path

SOURCE = Path('data/spots.json')
TARGET = Path('core/src/main/kotlin/de/keinbiervorvier/core/BeerSpotsData.kt')
# SwiftPM only bundles resources from inside the package, so it gets a copy.
SWIFT_COPY = Path('ios/BeerCore/Sources/BeerCore/Resources/spots.json')


def q(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def geo(item):
    return f"GeoPoint({item['lat']}, {item['lon']})"


def brewery(b):
    args = [q(b['name'])]
    if 'town' in b:
        args += [q(b['town']), geo(b)]
    if 'website' in b:
        args.append(f"website = {q(b['website'])}")
    return f"Brewery({', '.join(args)})"


def spot(s):
    if s['breweries']:
        inner = ''.join(f'                {brewery(b)},\n' for b in s['breweries'])
        breweries = f'listOf(\n{inner}            )'
    else:
        breweries = 'emptyList()'
    short = f",\n            shortName = {q(s['short'])}" if 'short' in s else ''
    return (f"        BeerSpot(\n            {q(s['city'])}, {q(s['zone'])}, {q(s['country'])}, {geo(s)},\n"
            f"            {breweries}{short},\n        ),\n")


def generate():
    spots = json.loads(SOURCE.read_text(encoding='utf-8'))['spots']
    english = ''.join(
        f"        {q(s['zone'])} to EnglishName({q(s['cityEn'])}"
        + (f", {q(s['shortEn'])}" if 'shortEn' in s else '') + '),\n'
        for s in spots if 'cityEn' in s)
    towns = sorted({(b['town'], b['townEn']) for s in spots for b in s['breweries'] if 'townEn' in b})
    english_towns = ''.join(f'        {q(de)} to {q(en)},\n' for de, en in towns)
    return f'''// Generated by tools/make_spots.py from data/spots.json - edit the JSON, not this file.
package de.keinbiervorvier.core

/**
 * One well-known city per distinct UTC offset (including the odd half- and
 * quarter-hour ones), ordered from east to west, each with a small selection
 * of breweries. Central Europe has three spots (Germany, France, Belgium)
 * that take turns, like their breweries.
 */
object BeerSpots {{
    val ALL: List<BeerSpot> = listOf(
{''.join(spot(s) for s in spots)}    )

    /** English names where they differ from the German ones, keyed by zone id. */
    val ENGLISH_NAMES: Map<String, EnglishName> = mapOf(
{english}    )

    /** English names of brewery towns where they differ from the German ones. */
    val ENGLISH_TOWNS: Map<String, String> = mapOf(
{english_towns}    )
}}
'''


if __name__ == '__main__':
    code = generate()
    data = SOURCE.read_text(encoding='utf-8')
    if '--check' in sys.argv:
        for path, content in [(TARGET, code), (SWIFT_COPY, data)]:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                sys.exit(f'{path} is out of date - run: python tools/make_spots.py')
        print('ok, up to date')
    else:
        TARGET.write_text(code, encoding='utf-8', newline='\n')
        SWIFT_COPY.write_text(data, encoding='utf-8', newline='\n')
        print('wrote', TARGET, 'and', SWIFT_COPY)
