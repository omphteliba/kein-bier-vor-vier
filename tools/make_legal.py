"""Turns the legal notice and privacy policy in docs/ into pages of the web app,
so the text is written once and GitHub, Play Store and website show the same.
Run from the repository root after editing docs/impressum.md or docs/privacy.md:

    python tools/make_legal.py           # write web/impressum.html, web/datenschutz.html
    python tools/make_legal.py --check   # fail if they are out of date (CI)

Understands just the Markdown these files use: headings, paragraphs, lists,
**bold**, [links](url) and a backslash at the end of a line for a line break.
"""
import html
import re
import sys
from pathlib import Path

PAGES = [
    (Path('docs/impressum.md'), Path('web/impressum.html'), 'Impressum · Legal notice'),
    (Path('docs/privacy.md'), Path('web/datenschutz.html'), 'Datenschutz · Privacy'),
]
BACKSLASH = chr(92)


def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)

    def link(m):
        label, url = m.group(1), m.group(2)
        external = url.startswith(('http://', 'https://'))
        attrs = ' rel="noopener"' if external else ''
        return f'<a href="{html.escape(url)}"{attrs}>{label}</a>'

    text = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', link, text)
    # Bare web addresses become links too.
    text = re.sub(r'(?<![">])(https://[^\s<]+[^\s<.,;:)])', r'<a href="\1" rel="noopener">\1</a>', text)
    return text


def slug(text):
    return {'Deutsch': 'deutsch', 'English': 'english'}.get(text, '')


def to_html(markdown):
    out, para, items = [], [], []

    def flush():
        if para:
            parts = []
            for line in para:
                if line.endswith(BACKSLASH):
                    parts.append(inline(line[:-1]) + '<br>')
                else:
                    parts.append(inline(line))
            out.append('<p>' + '\n'.join(parts) + '</p>')
            para.clear()
        if items:
            out.append('<ul>\n' + '\n'.join(f'<li>{inline(i)}</li>' for i in items) + '\n</ul>')
            items.clear()

    for line in markdown.splitlines():
        line = line.rstrip()
        heading = re.match(r'(#{1,3}) (.+)', line)
        if not line:
            flush()
        elif heading:
            flush()
            level, text = len(heading.group(1)), heading.group(2)
            ident = slug(text)
            out.append(f'<h{level}' + (f' id="{ident}"' if ident else '') + f'>{inline(text)}</h{level}>')
        elif line.startswith('- '):
            if para:
                flush()
            items.append(line[2:])
        else:
            if items:
                flush()
            para.append(line)
    flush()
    return '\n'.join(out)


def page(title, body):
    return f'''<!doctype html>
<!-- Generated by tools/make_legal.py from docs/ – edit the Markdown there. -->
<html lang="de">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title} – Irgendwo ist immer Vier</title>
  <meta name="color-scheme" content="light">
  <link rel="icon" type="image/png" href="icons/vier-64.png">
  <link rel="stylesheet" href="css/style.css">
</head>
<body>
  <main class="legal">
    <p><a class="back" href="./">← Irgendwo ist immer Vier · 5 O'Clock Somewhere</a></p>
{body}
    <footer>
      <p class="links"><a href="impressum.html">Impressum · Legal notice</a> · <a href="datenschutz.html">Datenschutz · Privacy</a></p>
    </footer>
  </main>
</body>
</html>
'''


def main():
    check = '--check' in sys.argv
    stale = []
    for source, target, title in PAGES:
        text = page(title, to_html(source.read_text(encoding='utf-8')))
        if check:
            if not target.exists() or target.read_text(encoding='utf-8') != text:
                stale.append(str(target))
        else:
            target.write_text(text, encoding='utf-8', newline='\n')
            print(f'wrote {target}')
    if stale:
        sys.exit('Out of date, run python tools/make_legal.py: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
